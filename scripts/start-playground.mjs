import express from 'express';
import {mkdirSync,readFileSync,writeFileSync,existsSync} from 'node:fs';
import {randomBytes} from 'node:crypto';
import {sqliteLiveStore} from '../src/accord/live-store.mjs';
import {createPlaygroundService} from '../src/accord/playground-service.mjs';
import {createLiveService} from '../src/accord/live-service.mjs';
import {createLiveNegotiation} from '../src/accord/live-negotiation.mjs';
import {liveHandler} from '../src/accord/live-http.mjs';
import {PUBLIC_CSP} from '../src/deal-escrow/public-files.mjs';
const port=Number(process.env.PLAYGROUND_PORT??3451);
mkdirSync('data/private/playground',{recursive:true});
const keyFile='data/private/playground/signing-secret';
if(!process.env.ACCORD_LIVE_SECRET&&!existsSync(keyFile))writeFileSync(keyFile,randomBytes(40).toString('hex'),{flag:'wx'});
const secret=process.env.ACCORD_LIVE_SECRET??readFileSync(keyFile,'utf8');
const store=sqliteLiveStore('data/private/playground/ledger.sqlite');
const operatorStore=sqliteLiveStore('data/private/playground/operator-ledger.sqlite');
const app=express();app.disable('x-powered-by');
app.use((_req,res,next)=>{res.setHeader('Content-Security-Policy',PUBLIC_CSP.replace("script-src 'self'","script-src 'self' 'wasm-unsafe-eval' 'unsafe-eval'").replace("connect-src 'self'","connect-src 'self' data:"));next();});
app.use(express.json({limit:'16kb'}));
const options={secret,secure:false,configured:!!process.env.KILN_API_KEY&&process.env.KILN_MODEL==='qwen3-32b'};
const playground=liveHandler({...options,service:createPlaygroundService({store,secret,callBudget:Number(process.env.ACCORD_PLAYGROUND_CALL_BUDGET??60)})});
const operator=liveHandler({...options,service:createLiveService({store:operatorStore,negotiation:createLiveNegotiation({secret}),callBudget:Number(process.env.ACCORD_LIVE_CALL_BUDGET??60)})});
app.all('/api/live',(req,res)=>req.query.playground==='1'?playground(req,res):operator(req,res));
app.use(express.static('dist-vercel',{dotfiles:'deny'}));
const server=app.listen(port,'127.0.0.1',()=>console.log(`Live Playground: http://127.0.0.1:${port}/#playground · Real Kiln / test ledger`));
for(const signal of ['SIGINT','SIGTERM'])process.on(signal,()=>server.close(()=>{store.close();operatorStore.close();process.exit(0);}));
